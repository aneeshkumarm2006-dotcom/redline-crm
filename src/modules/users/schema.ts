import { z } from "zod";

export const roleSchema = z.enum(["owner", "salesperson"]);
export type Role = z.infer<typeof roleSchema>;
export const userIdSchema = z.string().regex(/^[a-f0-9]{24}$/i);
export const emailSchema = z.string().trim().toLowerCase().email().max(254);
export const userSchema = z.object({
  id: userIdSchema, name: z.string().trim().min(1).max(120), email: emailSchema,
  role: roleSchema, dealershipId: userIdSchema.nullable(), active: z.boolean(),
  // Optional profile fields (v2). Defaults keep accounts created before them valid.
  phone: z.string().trim().min(7).max(40).nullable().default(null),
  // Units the salesperson aims to sell per month; null when no target is set.
  monthlyTarget: z.number().int().min(0).max(1000).nullable().default(null),
  hiredAt: z.string().datetime({ offset: true }).nullable().default(null),
});
export type User = z.infer<typeof userSchema>;
export const initializeUserSchema = userSchema.omit({ id: true }).extend({
  passwordHash: z.string().regex(/^\$2[aby]\$12\$[./A-Za-z0-9]{53}$/),
}).strict();

// Owner staff admin. Role is fixed to salesperson; credentials are generated by the service, never accepted.
const optionalPhone = z.string().trim().min(7).max(40).nullable().default(null);
export const staffFormSchema = z.object({
  name: z.string().trim().min(1).max(120), email: emailSchema, phone: optionalPhone,
  dealershipId: userIdSchema,
  monthlyTarget: z.number().int().min(0).max(1000).nullable().default(null),
  hiredAt: z.string().datetime({ offset: true }).nullable().default(null),
}).strict();
export const staffUpdateSchema = staffFormSchema.extend({ id: userIdSchema, active: z.boolean() }).strict();
export type StaffForm = z.infer<typeof staffFormSchema>;
export type StaffActionResult = { ok: true; id: string; temporaryPassword?: string } | { ok: false; message: string };
